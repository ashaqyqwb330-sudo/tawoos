٥. رسالة البرنامج
يسعى برنامج دبلوم الإسعاف الحربي إلى إعداد مسعف حربي ميداني متكامل – معالج، قائد، ومستشار – قادر على تقديم رعاية إسعافية وجراحية متقدمة في بيئات القتال والكوارث والحصار، باستخدام أحدث البروتوكولات العالمية (TCCC، ATLS، PHTLS) والتقنيات التشخيصية المحمولة (POCUS). يدمج البرنامج بين الفهم العميق للعلوم الطبية الأساسية والتطبيقات الميدانية، ويرسخ قيم القيادة، والعمل الجماعي، والتعلم الذاتي المستمر، والمسؤولية الأخلاقية والجهادية، بهدف إنقاذ الأرواح والحفاظ على الجاهزية القتالية للقوات المسلحة.

٦. أهداف البرنامج (12 هدفاً)
1. ترسيخ القيم الدينية والاعتزاز بالمنهج القرآني والعقيدة الجهادية، والالتزام بالأخلاقيات العسكرية والطبية.
2. تزويد الطالب بالمعرفة المتكاملة في التشريح، الفسيولوجيا، الفيزيولوجيا المرضية للإصابات الحربية والأمراض الباطنية الشائعة في البيئات المختلفة (حارة، باردة، ساحلية، جبلية).
3. تمكين الطالب من خيارات العلاج الدوائي (مسكنات، مضادات حيوية، أدوية طوارئ) وغير الدوائي (نقل الدم، الإنعاش، الجراحة الميدانية) وفق أحدث البروتوكولات العالمية.
4. إتقان التشخيص السريري المتقدم والاستدلال التفريقي باستخدام العلامات الحيوية، مقياس غلاسكو، أنظمة الفرز (MARCH)، والفحوصات السريعة (POCUS، غازات الدم، فصائل الدم).
5. إكساب الطالب المهارات الجراحية الميدانية المنقذة للحياة: السيطرة على النزيف، إدارة مجرى الهواء، بزل الصدر، البتر الميداني، فتح البطن الاستكشافي، وتحرير الحجرات.
6. إدارة الإصابات الجماعية (MASCAL) بتطبيق أنظمة الفرز (START، نظام الألوان)، وتنظيم ساحة الحادث، وتنسيق الإخلاء الطبي (CASEVAC/MEDEVAC).
7. التعرف على أسلحة الدمار الشامل (البيولوجية، الكيميائية، النووية) وطرق الوقاية، إزالة التلوث، والعلاج الأولي.
8. تطبيق مبادئ الصحة العامة العسكرية: الترصد الوبائي، مكافحة العدوى، سلامة المياه والغذاء، إدارة النفايات الطبية، برامج التطعيم.
9. إدارة المراكز الطبية الميدانية والموارد البشرية والمادية، والتخطيط للإخلاء، والتوثيق الدقيق باستخدام تقارير MIST/MIST-AT وسجل المهارات.
10. إدارة الرعاية المطولة (PFC) لمدة تصل إلى 48-72 ساعة في ظروف الحصار، بما في ذلك إدارة السوائل، التغذية، العناية بالجروح، والأدوية.
11. تنمية مهارات القيادة، العمل الجماعي، التواصل الفعال، إدارة الضغوط النفسية، والدعم النفسي الأولي في بيئات القتال.
12. تعزيز التعلم الذاتي المستمر، استخدام المصادر الرقمية (UpToDate, PubMed, Deployed Medicine)، وتطبيق معايير السلامة المهنية ومكافحة العدوى في الميدان.

